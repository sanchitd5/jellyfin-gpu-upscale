  function currentStage() {
    if (!state.stage || typeof state.stage !== "object") {
      return null;
    }
    var l = ladder();
    if (!l || !l.length) {
      return null;
    }
    var exact = l.filter(function(st) {
      return sameStage(st, state.stage);
    })[0];
    if (exact) {
      return exact;
    }
    var want = stageCost(
      parseInt((eligibleTargets()[Math.min(state.stage.rank, eligibleTargets().length - 1)] || {}).id, 10) || 1080,
      state.stage.sr,
      state.stage.denoise
    );
    var below = l.filter(function(st) {
      return st.cost <= want;
    });
    return below.length ? below[below.length - 1] : l[0];
  }
