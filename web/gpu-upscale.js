  function makeDraggable(head) {
    try {
      head.addEventListener("dblclick", function(ev) {
        if (!isControl(ev.target)) {
          resetPanelPos();
        }
      });
      if (!window.PointerEvent) {
        return;
      }
      head.addEventListener("pointerdown", function(ev) {
        try {
          let end = function() {
            try {
              document.removeEventListener("pointermove", onMove, true);
              document.removeEventListener("pointerup", onUp, true);
              document.removeEventListener("pointercancel", onUp, true);
              try {
                head.releasePointerCapture(d.id);
              } catch (e) {
              }
              if (d.moved) {
                savePrefs();
                window.addEventListener("click", eatClick, true);
                setTimeout(function() {
                  window.removeEventListener("click", eatClick, true);
                }, 0);
              }
            } catch (err) {
              log("drag cleanup failed", err);
            }
            state.drag = null;
          };
          if (ev.button != null && ev.button !== 0) {
            return;
          }
          if (isControl(ev.target)) {
            return;
          }
          var panel = panelEl();
          if (!panel) {
            return;
          }
          var r = panel.getBoundingClientRect();
          var d = {
            id: ev.pointerId,
            ox: ev.clientX - r.left,
            oy: ev.clientY - r.top,
            sx: ev.clientX,
            sy: ev.clientY,
            moved: false
          };
          var eatClick = function(e3) {
            e3.stopPropagation();
            e3.preventDefault();
          };
          var onMove = function(e2) {
            try {
              if (!state.drag || e2.pointerId !== d.id) {
                return;
              }
              if (!d.moved && Math.abs(e2.clientX - d.sx) < DRAG_SLOP && Math.abs(e2.clientY - d.sy) < DRAG_SLOP) {
                return;
              }
              if (!d.moved) {
                d.moved = true;
                try {
                  head.setPointerCapture(d.id);
                } catch (e) {
                }
              }
              if (e2.cancelable) {
                e2.preventDefault();
              }
              state.panelPos = { x: e2.clientX - d.ox, y: e2.clientY - d.oy };
              applyPanelPos();
            } catch (err) {
              log("drag failed", err);
              end();
            }
          };
          var onUp = function(e4) {
            if (e4.pointerId === d.id) {
              end();
            }
          };
          state.drag = d;
          document.addEventListener("pointermove", onMove, true);
          document.addEventListener("pointerup", onUp, true);
          document.addEventListener("pointercancel", onUp, true);
        } catch (err) {
          log("drag failed to start", err);
          state.drag = null;
        }
      });
    } catch (err) {
      log("could not make the panel draggable", err);
    }
  }
  function gripButton() {
    var g = el("button", "gpuup-grip", "\u283F");
    g.type = "button";
    g.title = "Drag to move. Arrow keys move it; Enter puts it back.";
    g.setAttribute("aria-label", "Move panel. Arrow keys move it, Enter resets its position.");
    g.onkeydown = function(ev) {
      var step = ev.shiftKey ? KEY_STEP * 3 : KEY_STEP;
      var dx = 0;
      var dy = 0;
      if (ev.key === "ArrowLeft") {
        dx = -step;
      } else if (ev.key === "ArrowRight") {
        dx = step;
      } else if (ev.key === "ArrowUp") {
        dy = -step;
      } else if (ev.key === "ArrowDown") {
        dy = step;
      } else {
        return;
      }
      ev.preventDefault();
      ev.stopPropagation();
      movePanelBy(dx, dy);
    };
    g.onclick = function(ev) {
      ev.stopPropagation();
      resetPanelPos();
    };
    return g;
  }
